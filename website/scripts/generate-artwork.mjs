// Rebuild the native constants from assets/mushroom-art.json after an art edit.
import {readFile,writeFile} from 'node:fs/promises';
import {artwork} from './mushroom-art.mjs';
const lines=['// Generated by website/scripts/generate-artwork.mjs; edit assets/mushroom-art.json.'];
lines.push(`pub const PALETTE_LEN: usize = ${14+artwork.colors.length};`);
lines.push(`const APPROVED_COLORS: [(u32, usize); ${artwork.colors.length}] = [`);
for(const {rgb,family} of artwork.colors)lines.push(`    (0x${(rgb[0]|rgb[1]<<8|rgb[2]<<16).toString(16).padStart(6,'0')}, ${family}),`);
lines.push('];');
for(const [key,name,width,height]of[['hero','HERO','HERO_WIDTH','HERO_HEIGHT'],['mini','MINI','LOGO_WIDTH','LOGO_HEIGHT'],['compact','COMPACT','COMPACT_WIDTH','COMPACT_HEIGHT'],['micro','MICRO','MICRO_WIDTH','MICRO_HEIGHT']]){
 const art=artwork[key];
 if(art.rows.length!==art.height||art.rows.some(row=>row.length!==art.width)||art.tones.some((row,y)=>row.length!==art.width||row.some((v,x)=>(v===255)!==(art.rows[y][x]==='.')||v!==255&&(v<14||v>=14+artwork.colors.length))))throw Error(`Invalid ${name} grid`);
 lines.push(`pub const ${width}: usize = ${art.width};`,`pub const ${height}: usize = ${art.height};`,`pub const ${name}: [&[u8; ${width}]; ${height}] = [`);
 for(const row of art.rows)lines.push(`    b"${row}",`);lines.push('];');
 lines.push(`pub const ${name}_TONES: [[u8; ${width}]; ${height}] = [`);
 for(const row of art.tones)lines.push(`    [${row.join(',')}],`);lines.push('];');
}
lines.push(`pub const HERO_SPOTS: [(usize, usize, usize, usize); 3] = [${artwork.spots.map(p=>`(${p.join(', ')})`).join(', ')}];`);
lines.push('const NAV_LOGO: [&str; 12] = [');
for(let y=0;y<12;y++){let row='';for(let x=0;x<12;x++){const glyph=artwork.micro.rows[Math.floor((2*y+1)*16/24)][Math.floor((2*x+1)*16/24)];row+=glyph!=='.'&&!'WVQ'.includes(glyph)?'X':'.';}lines.push(`    "${row}",`);}lines.push('];');
const destination=new URL('../../native/src/mushroom_data.rs',import.meta.url),content=lines.join('\n')+'\n';
if(process.argv.includes('--check')){
 if(await readFile(destination,'utf8')!==content)throw Error('Native artwork is stale; run generate-artwork.mjs');
 console.log('Native artwork matches the shared source');
}else{
 await writeFile(destination,content);
 console.log('Generated shared native artwork and theme-relative tones');
}
